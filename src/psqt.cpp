Score psqtTable[PIECE_NB][SQUARE_NB];

void initPSQT() {
    for (PieceType pt = PAWN; pt <= KING; ++pt)
        for (Square sq = SQ_A1; sq <= SQ_H8; ++sq) {
            psqtTable[makePiece(WHITE, pt)][sq] = PSQT_TABLE[pt][sq] + PIECE_VALUES[pt];
            psqtTable[makePiece(BLACK, pt)][sq ^ 56] = -psqtTable[makePiece(WHITE, pt)][sq];
        }
}
